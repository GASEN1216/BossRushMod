        internal static void RestoreMissingParts(Transform world)
        {
            Transform collision = world.Find("Collision");
            Transform objects = collision == null ? null : collision.Find("COL_Objects");
            if (objects == null) return;
            Transform holder = objects;
            if (!objects.gameObject.activeSelf)
            {
                // 作者分组关闭时，补件挂在可独立启用的同级分组下。
                holder = collision.Find("COL_RestoredObjects");
                if (holder == null)
                {
                    holder = new GameObject("COL_RestoredObjects").transform;
                    holder.SetParent(collision, false);
                }
            }
            foreach (Part part in MissingParts)
            {
                Transform existing = holder.Find(part.Name);
                if (existing != null)
                {
                    BoxCollider solid = existing.GetComponent<BoxCollider>();
                    if (solid != null && solid.enabled && !solid.isTrigger && existing.gameObject.activeSelf) continue;
                    existing.gameObject.name += "_Inactive";
                }
                var node = new GameObject(part.Name).transform;
                node.SetParent(holder, false);
                node.localPosition = part.Center;
                node.localRotation = Quaternion.Euler(0f, part.Yaw, 0f);
                node.gameObject.AddComponent<BoxCollider>().size = part.Size;
            }
        }
